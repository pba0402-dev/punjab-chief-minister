/**
 * Keep the PHP candidate table identical to the JavaScript one.
 * ------------------------------------------------------------------
 * A solo game rolls in js/engine/campaign.js and a multiplayer game rolls in
 * api/lib/Campaign.php. Both multiply a campaign by the candidate's support
 * in that region, so if the two tables of numbers ever stopped matching the
 * same move would produce a different board depending on who you played with.
 *
 * Rather than trust two hand-kept copies, this generates the PHP one from the
 * JavaScript one, which is the source of truth. `npm run test:campaign` fails
 * if the generated file is out of date, so a forgotten regeneration is a
 * failing build rather than a quiet divergence.
 *
 *   node tools/sync-candidates.mjs          write api/lib/Candidates.php
 *   node tools/sync-candidates.mjs --check  fail if it would change anything
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..');
const SRC = path.join(ROOT, 'simple/js/data/candidates.js');
const OUT = path.join(ROOT, 'simple/api/lib/Candidates.php');

/** Read the JavaScript table by running it, rather than by parsing it. */
function readTable() {
  const src = fs.readFileSync(SRC, 'utf8');
  const sandbox = { window: {} };
  /*
   * The file is plain ES5 against a `window` global and touches nothing else.
   *
   * In a browser `window.CMP = ...` also creates a bare `CMP` global, which
   * is what the rest of the file writes to; inside a Function it does not, so
   * the binding is made here before the source runs.
   */
  const preamble = 'var CMP = window.CMP = window.CMP || {};\n';
  new Function('window', preamble + src)(sandbox.window);
  const CMP = sandbox.window.CMP;
  if (!CMP || !CMP.CANDIDATE_STATS) throw new Error('no CANDIDATE_STATS in ' + SRC);
  return {
    stats: CMP.CANDIDATE_STATS,
    neutral: CMP.REGION_NEUTRAL,
    swing: CMP.REGION_SWING,
  };
}

function php(table) {
  const rows = Object.keys(table.stats).map((id) => {
    const c = table.stats[id];
    const r = c.regionalSupport || {};
    const regions = Object.keys(r)
      .map((k) => `                '${k}' => ${r[k]},`)
      .join('\n');
    return [
      `        '${id}' => [`,
      `            'popularity' => ${c.popularity},`,
      `            'corruption' => ${c.corruption},`,
      `            'leadership' => ${c.leadership},`,
      `            'campaignStrength' => ${c.campaignStrength},`,
      `            'regionalSupport' => [`,
      regions,
      `            ],`,
      `        ],`,
    ].join('\n');
  }).join('\n');

  return `<?php
/**
 * The cast, and what each of them is like — server side.
 * ------------------------------------------------------------------
 * GENERATED by tools/sync-candidates.mjs from js/data/candidates.js.
 * Do not edit by hand: edit the JavaScript and run the tool.
 *
 * A solo game rolls in the browser and a multiplayer game rolls here. Both
 * multiply a campaign by the candidate's support in that region, so these
 * numbers and the ones in the JavaScript have to be the same numbers. The
 * campaign suite fails if this file is out of date.
 */

class Candidates
{
    /** Neutral, in the units regionalSupport is written in. */
    public const REGION_NEUTRAL = ${table.neutral};

    /** What a 100 or a 0 is worth, either side of neutral. */
    public const REGION_SWING = ${table.swing};

    private const STATS = [
${rows}
    ];

    /**
     * What a face is worth, with a safe answer for one nobody wrote down.
     *
     * An id from a future list, or a save older than this table, is neutral
     * everywhere rather than an error — the same fallback the JavaScript uses.
     */
    public static function statsFor(string $avatarId): array
    {
        if (isset(self::STATS[$avatarId])) {
            return self::STATS[$avatarId];
        }

        return [
            'popularity' => 50,
            'corruption' => 25,
            'leadership' => 50,
            'campaignStrength' => 50,
            'regionalSupport' => ['majha' => 50, 'doaba' => 50, 'malwa' => 50],
        ];
    }

    /** Every id this table knows, for the tool that checks the two agree. */
    public static function ids(): array
    {
        return array_keys(self::STATS);
    }
}
`;
}

const table = readTable();
const wanted = php(table);
const check = process.argv.includes('--check');
const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';

if (check) {
  if (current !== wanted) {
    console.error('api/lib/Candidates.php is out of date.');
    console.error('Run: node tools/sync-candidates.mjs');
    process.exit(1);
  }
  console.log('candidates: PHP matches JavaScript');
} else {
  fs.writeFileSync(OUT, wanted);
  console.log('wrote ' + path.relative(ROOT, OUT) +
    ' (' + Object.keys(table.stats).length + ' candidates)');
}
