/**
 * Generates simple/js/data/incumbents.js from tools/incumbents.json.
 *
 * Joins sitting MLAs onto the verified 117 constituencies BY NAME, applies the
 * by-election overrides, and refuses to emit anything if a single seat fails to
 * match. Silent gaps are worse than a failed build: this is real data about
 * real people, and a wrong pairing would put the wrong name on a seat.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const acs = JSON.parse(fs.readFileSync(path.join(HERE, 'acs.json'), 'utf8'));
const src = JSON.parse(fs.readFileSync(path.join(HERE, 'incumbents.json'), 'utf8'));

/** Loose key so "Sri Khadoor Sahib" and "Khadur Sahib" meet in the middle. */
const key = (s) =>
  String(s)
    .toLowerCase()
    .replace(/\(.*?\)/g, '')
    .replace(/\b(sri|shri|sahib)\b/g, '')
    .replace(/[^a-z]/g, '');

const base = new Map();
for (const [name, [mla, party]] of Object.entries(src.base)) {
  base.set(key(name), { name, mla, party });
}

const overrides = new Map();
for (const b of src.byElections) {
  overrides.set(key(b.constituency), b);
}

const problems = [];
const usedBase = new Set();
const usedOverride = new Set();

const incumbents = acs.map((row) => {
  const [number, name, district, reservation] = row;
  const k = key(name);

  const entry = base.get(k);
  if (!entry) {
    problems.push(`AC ${number} ${name}: no sitting MLA found`);
    return null;
  }
  usedBase.add(k);

  let mla = entry.mla;
  let party = entry.party;
  let since = null;
  let byElection = null;

  const over = overrides.get(k);
  if (over) {
    usedOverride.add(k);
    mla = over.mla;
    party = over.party;
    since = over.date;
    byElection = { date: over.date, reason: over.reason, previous: entry.mla, previousParty: entry.party };
  }

  return {
    number,
    name,
    district,
    reserved: reservation === 'SC' ? 'SC' : null,
    mla,
    party,
    since,
    byElection,
  };
});

/* Nothing may be left over on either side. */
for (const [k, v] of base) {
  if (!usedBase.has(k)) problems.push(`Unmatched MLA record: "${v.name}" (${v.mla})`);
}
for (const [k, v] of overrides) {
  if (!usedOverride.has(k)) problems.push(`Unmatched by-election: "${v.constituency}"`);
}
if (incumbents.some((i) => i === null)) problems.push('one or more seats had no MLA');

if (problems.length) {
  console.error('Incumbent data did not join cleanly:');
  problems.forEach((p) => console.error('  - ' + p));
  process.exit(1);
}

/* Party strengths, for the baseline the game starts from. */
const byParty = {};
for (const i of incumbents) byParty[i.party] = (byParty[i.party] || 0) + 1;

const body = `/**
 * Sitting MLAs of the ${src.assembly}.
 * GENERATED by tools/build-incumbents.mjs — do not edit here.
 * Edit tools/incumbents.json and run: npm run data:incumbents
 *
 * REAL REFERENCE DATA, current as of ${src.asOf}. These are real people holding
 * real seats. They are the incumbents the fictional game is played against and
 * they take no part in it: the players are invented candidates, and every
 * campaign action, support figure and result in this game is fiction.
 */
window.CMP = window.CMP || {};

CMP.INCUMBENTS_AS_OF = ${JSON.stringify(src.asOf)};
CMP.ASSEMBLY_NAME = ${JSON.stringify(src.assembly)};

CMP.INCUMBENTS = ${JSON.stringify(incumbents, null, 0)};

/** Seats held by each party at the start — the game's political baseline. */
CMP.INCUMBENT_STRENGTH = ${JSON.stringify(byParty, null, 0)};

CMP.INCUMBENT_BY_NUMBER = (function () {
  var map = {};
  for (var i = 0; i < CMP.INCUMBENTS.length; i++) {
    map[CMP.INCUMBENTS[i].number] = CMP.INCUMBENTS[i];
  }
  return map;
})();

CMP.getIncumbent = function (number) {
  return CMP.INCUMBENT_BY_NUMBER[number] || null;
};
`;

const out = path.join(HERE, '..', 'simple', 'js', 'data', 'incumbents.js');
fs.writeFileSync(out, body);

console.log('incumbents joined: ' + incumbents.length + ' / 117');
console.log('by-elections applied: ' + usedOverride.size + ' / ' + overrides.size);
console.log(
  'party strength: ' +
    Object.entries(byParty)
      .sort((a, b) => b[1] - a[1])
      .map(([p, n]) => p + ' ' + n)
      .join(', ')
);
console.log('total check: ' + Object.values(byParty).reduce((a, b) => a + b, 0));
console.log('as of: ' + src.asOf);
console.log('written: ' + path.relative(path.join(HERE, '..'), out));
