/**
 * Generates simple/js/data/geometry.js — the shapes the constituency map draws.
 *
 * Source is src/data/punjab-geometry.js, produced by tools/build-geometry.mjs
 * from the same verified constituency list this game uses. See the header
 * written into the output for exactly what the shapes are and are not.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..');

const src = fs.readFileSync(path.join(ROOT, 'src/data/punjab-geometry.js'), 'utf8');
const GEO = JSON.parse(src.slice(src.indexOf('PG.GEOMETRY = ') + 14, src.lastIndexOf(';')));
const acs = JSON.parse(fs.readFileSync(path.join(HERE, 'acs.json'), 'utf8'));

/* The map must line up with the constituency list exactly, or a seat would be
   drawn in the wrong place. Fail rather than ship a mismatch. */
const problems = [];
if (GEO.seats.length !== acs.length) {
  problems.push('geometry has ' + GEO.seats.length + ' seats, data has ' + acs.length);
}
for (const row of acs) {
  if (!GEO.seats.some((s) => s.num === row[0])) problems.push('no shape for AC ' + row[0] + ' ' + row[1]);
}
for (const s of GEO.seats) {
  if (!s.cell || s.cell.length < 3) problems.push('AC ' + s.num + ' has no usable cell');
  if (!s.hex || s.hex.length !== 2) problems.push('AC ' + s.num + ' has no hex tile');
}
if (problems.length) {
  console.error('Map geometry does not match the constituency data:');
  problems.slice(0, 10).forEach((p) => console.error('  - ' + p));
  process.exit(1);
}

/* Trim to what the map actually draws. */
const out = {
  viewBox: GEO.viewBox,
  outline: GEO.outline,
  hexPoints: GEO.hexPoints,
  hexSize: GEO.hexSize,
  seats: GEO.seats.map((s) => ({
    num: s.num,
    cell: s.cell,
    centroid: s.centroid,
    hex: s.hex,
  })),
  districts: Object.fromEntries(
    Object.entries(GEO.districts).map(([name, d]) => [
      name,
      { short: d.short || name, centroid: d.centroid, hexCentroid: d.hexCentroid, border: d.border, hexBorder: d.hexBorder },
    ])
  ),
};

const body = `/**
 * Map geometry for the 117 constituencies.
 * GENERATED by tools/build-map-data.mjs — do not edit here.
 *
 * WHAT THESE SHAPES ARE
 *   The state outline is the real boundary of Punjab from OpenStreetMap.
 *   Each constituency's position comes from the geocoded centre of its town,
 *   with city-ward seats placed by hand (the Amritsar, Jalandhar and Ludhiana
 *   wards). The cells are a Voronoi tessellation of those real positions,
 *   clipped to the real state outline.
 *
 * WHAT THEY ARE NOT
 *   They are NOT official constituency boundaries, and no boundary has been
 *   invented to look like one. Position and adjacency are faithful — every
 *   seat sits where it really is, next to the seats it really borders — and
 *   the shape of each cell is an approximation of the area it covers. The map
 *   labels itself as approximate, and a tile view is offered alongside it that
 *   makes no geographic claim at all.
 */
window.CMP = window.CMP || {};

CMP.GEOMETRY = ${JSON.stringify(out)};
`;

const dest = path.join(ROOT, 'simple/js/data/geometry.js');
fs.writeFileSync(dest, body);

console.log('seats: ' + out.seats.length);
console.log('districts: ' + Object.keys(out.districts).length);
console.log('viewBox: ' + out.viewBox.width + ' x ' + out.viewBox.height);
console.log('written: ' + (fs.statSync(dest).size / 1024).toFixed(0) + ' KB');
